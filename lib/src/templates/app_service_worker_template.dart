/// Placeholder replaced by the generator with the table JSON.
const tableToken = '__APP_SW_TABLE__';

const appServiceWorkerTemplate = r'''
'use strict';

// Generated by pillar_web_sw. Do not edit; rerun the generator.
const TABLE = __APP_SW_TABLE__;

const PREFIX = TABLE.cachePrefix;
const CORE_CACHE = PREFIX + '-core-' + TABLE.releaseId;
// Never the name of a live release: the active worker may be serving
// CORE_CACHE (same core, other worker) while this one installs.
const INSTALLING_CACHE = CORE_CACHE + '-installing';
const ONDEMAND_CACHE = PREFIX + '-ondemand';
const RUNTIME_CACHE = PREFIX + '-runtime';
const META_CACHE = PREFIX + '-meta';
const LEGACY_CACHES = [
  'flutter-app-cache',
  'flutter-temp-cache',
  'flutter-app-manifest',
];
const NAVIGATION_TIMEOUT_MS = 3000;
const RUNTIME_MAX_ENTRIES = 60;
const INSTALL_CONCURRENCY = 6;
const CONFIG_REL = 'config.js';
const INDEX_REL = 'index.html';
// Missing files under these paths must be a real 404, never index.html.
const STATIC_PREFIXES = ['assets/', 'canvaskit/', 'icons/', 'main.dart'];

const BASE = new URL(self.registration.scope);
const pathOf = (rel) => new URL(rel, BASE).pathname;
const hrefOf = (rel) => new URL(rel, BASE).href;
const CORE = new Map(TABLE.core.map((e) => [pathOf(e.url), e]));
const ON_DEMAND = new Map(TABLE.onDemand.map((e) => [pathOf(e.url), e]));
const CONFIG_PATH = pathOf(CONFIG_REL);
const ERROR_KEY = hrefOf('__app-sw__/last-install-error');
const CONFIG_ERROR_KEY = hrefOf('__app-sw__/config-prefetch-error');
const FIRST_INSTALL_KEY = hrefOf('__app-sw__/first-install');

let state = 'parsed';

// ---- install -------------------------------------------------------------

self.addEventListener('install', (event) => {
  state = 'installing';
  event.waitUntil(install());
});

async function install() {
  // The first page load asks for config.js before this worker controls it,
  // so only the install can get it into the cache for the offline reopen.
  await markFirstInstall(!self.registration.active);
  try {
    await precacheCore();
    await promoteInstalled();
    await prefetchConfig();
    state = 'installed';
  } catch (error) {
    state = 'failed';
    const message = String((error && error.message) || error);
    console.error('[app-sw] install failed: ' + message);
    await recordInstallError(message);
    await caches.delete(INSTALLING_CACHE);
    // Rejecting keeps the previous worker in charge.
    throw error;
  }
}

async function precacheCore() {
  await caches.delete(INSTALLING_CACHE);
  const cache = await caches.open(INSTALLING_CACHE);
  // config.js is per tenant and changes without a new build: it is never
  // part of the release, so it cannot be hash-checked either.
  const queue = TABLE.core.filter((e) => e.url !== CONFIG_REL);
  if (TABLE.navigationFallback && !queue.some((e) => e.url === INDEX_REL)) {
    throw new Error(INDEX_REL + ' is not in the core');
  }
  const lanes = Array.from(
    { length: Math.min(INSTALL_CONCURRENCY, queue.length) },
    async () => {
      try {
        while (queue.length) await precacheEntry(cache, queue.shift());
      } catch (error) {
        queue.length = 0;
        throw error;
      }
    },
  );
  await Promise.all(lanes);
}

// Copies the verified entries to the final name. Existing entries are only
// overwritten (same release id means same content), never deleted, so a
// failure cannot take away a cache another worker is serving.
async function promoteInstalled() {
  const existed = await caches.has(CORE_CACHE);
  try {
    const temp = await caches.open(INSTALLING_CACHE);
    const target = await caches.open(CORE_CACHE);
    for (const request of await temp.keys()) {
      await target.put(request.url, await temp.match(request.url));
    }
  } catch (error) {
    if (!existed) await caches.delete(CORE_CACHE);
    throw error;
  }
  await caches.delete(INSTALLING_CACHE);
}

async function precacheEntry(cache, entry) {
  const href = hrefOf(entry.url);
  const response = await fetch(new Request(href, { cache: 'reload' }));
  if (response.status !== 200) {
    throw new Error(entry.url + ': status ' + response.status);
  }
  // Proxies rewrite HTML and text on the edge, so those entries are checked
  // by status only (entry.check === 'status'); TLS covers their integrity.
  if (entry.check === 'status') {
    await cache.put(href, response);
    return;
  }
  const copy = response.clone();
  const hash = await shortHash(await response.arrayBuffer());
  if (hash !== entry.hash) {
    throw new Error(entry.url + ': hash ' + hash + ' differs from ' + entry.hash);
  }
  await cache.put(href, copy);
}

async function shortHash(buffer) {
  const digest = await crypto.subtle.digest('SHA-256', buffer);
  const bytes = new Uint8Array(digest).slice(0, 4);
  return Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
}

// Best effort: a missing or failing config.js never rejects the install.
async function prefetchConfig() {
  await writeMeta(CONFIG_ERROR_KEY, null);
  try {
    const href = hrefOf(CONFIG_REL);
    const response = await fetch(new Request(href, { cache: 'reload' }));
    if (!response.ok || response.type !== 'basic') {
      throw new Error('config.js: status ' + response.status);
    }
    const cache = await caches.open(RUNTIME_CACHE);
    await cache.put(href, response);
  } catch (error) {
    await writeMeta(CONFIG_ERROR_KEY, String((error && error.message) || error));
  }
}

// The marker tells activate whether a worker of ours was already in charge.
// Judged here because the activate may run much later, in a new instance.
async function markFirstInstall(isFirst) {
  await writeMeta(FIRST_INSTALL_KEY, isFirst ? 'yes' : null);
}

async function takeFirstInstallMark() {
  const mark = await readMeta(FIRST_INSTALL_KEY);
  await writeMeta(FIRST_INSTALL_KEY, null);
  return mark === 'yes';
}

const recordInstallError = (message) => writeMeta(ERROR_KEY, message);
const readInstallError = () => readMeta(ERROR_KEY);

// Small notes live in a cache because a failed worker is discarded and the
// active one must still report them. Never served by fetch.
async function writeMeta(key, message) {
  try {
    const cache = await caches.open(META_CACHE);
    if (message === null) await cache.delete(key);
    else await cache.put(key, new Response(JSON.stringify({ message })));
  } catch (_) {
    // Reporting is best effort.
  }
}

async function readMeta(key) {
  try {
    const cache = await caches.open(META_CACHE);
    const hit = await cache.match(key);
    return hit ? (await hit.json()).message : null;
  } catch (_) {
    return null;
  }
}

// ---- activate ------------------------------------------------------------

self.addEventListener('activate', (event) => {
  state = 'activating';
  event.waitUntil(activate().then(() => { state = 'activated'; }));
});

async function activate() {
  const names = await caches.keys();
  const corePrefix = PREFIX + '-core-';
  const otherReleases = names.filter(
    (n) => n.startsWith(corePrefix) && n !== CORE_CACHE,
  );
  const doomed = otherReleases.concat(
    names.filter((n) => LEGACY_CACHES.includes(n)),
  );
  await Promise.all(doomed.map((n) => caches.delete(n)));
  await pruneOnDemand();
  await writeMeta(ERROR_KEY, null);
  // An update must not be swapped under pages running the old release; only
  // a first install (no active worker at install time) takes them over.
  if (await takeFirstInstallMark()) await self.clients.claim();
}

function onDemandKey(entry) {
  const href = hrefOf(entry.url);
  return entry.urlHashed ? href : href + '?v=' + entry.hash;
}

async function pruneOnDemand() {
  const keep = new Set(TABLE.onDemand.map(onDemandKey));
  const cache = await caches.open(ONDEMAND_CACHE);
  for (const request of await cache.keys()) {
    if (!keep.has(request.url)) await cache.delete(request);
  }
}

// ---- messages ------------------------------------------------------------

self.addEventListener('message', (event) => {
  const data = event.data;
  if (!data || typeof data.type !== 'string') return;
  if (data.type === 'app-sw-skip-waiting') {
    self.skipWaiting();
  } else if (data.type === 'app-sw-status') {
    event.waitUntil(replyStatus(event));
  }
});

async function replyStatus(event) {
  const target = (event.ports && event.ports[0]) || event.source;
  if (!target) return;
  target.postMessage({
    type: 'app-sw-status',
    releaseId: TABLE.releaseId,
    state: (self.serviceWorker && self.serviceWorker.state) || state,
    lastInstallError: await readInstallError(),
    configPrefetchError: await readMeta(CONFIG_ERROR_KEY),
  });
}

// ---- fetch ---------------------------------------------------------------

self.addEventListener('fetch', (event) => {
  const handler = route(event.request);
  if (handler) event.respondWith(handler(event));
});

// Returns a handler, or null to leave the request to the browser.
function route(request) {
  if (request.method !== 'GET' || request.headers.has('range')) return null;
  const url = new URL(request.url);
  if (url.origin !== BASE.origin) return isCdn(url) ? revalidating : null;
  if (!url.pathname.startsWith(BASE.pathname)) return null;
  const rel = url.pathname.slice(BASE.pathname.length);
  if (isNeverIntercepted(url, rel)) return null;
  const isStatic = STATIC_PREFIXES.some((p) => rel.startsWith(p));
  if (url.pathname === CONFIG_PATH) return networkFirst;
  if (request.mode === 'navigate' && TABLE.navigationFallback && !isStatic) {
    return navigation;
  }
  const core = CORE.get(url.pathname);
  if (core) return releaseFirst;
  const onDemand = ON_DEMAND.get(url.pathname);
  if (onDemand) return (event) => onDemandFirst(event, onDemand);
  return null;
}

function isCdn(url) {
  if (url.hostname === 'fonts.gstatic.com') return true;
  return (
    url.hostname === 'www.gstatic.com' &&
    url.pathname.startsWith('/flutter-canvaskit/')
  );
}

function isNeverIntercepted(url, rel) {
  return TABLE.neverIntercept.some(
    (p) => url.pathname.startsWith(p) || ('/' + rel).startsWith(p),
  );
}

// Navigation: network first, this release's index.html when the network is
// slow, down or failing.
async function navigation(event) {
  const network = fetch(event.request);
  network.catch(() => {});
  const timeout = new Promise((resolve) =>
    setTimeout(() => resolve(null), NAVIGATION_TIMEOUT_MS),
  );
  let response = null;
  try {
    response = await Promise.race([network, timeout]);
  } catch (_) {
    response = null;
  }
  if (response && response.status < 500) return response;
  const cache = await caches.open(CORE_CACHE);
  const index = await cache.match(hrefOf(INDEX_REL), { ignoreSearch: true });
  if (index) return index;
  return response || network;
}

// Core entries come from the cache of the release that served index.html,
// so wasm, loader and html never mix releases.
async function releaseFirst(event) {
  const cache = await caches.open(CORE_CACHE);
  const hit = await cache.match(event.request.url, { ignoreSearch: true });
  return hit || fetch(event.request);
}

async function networkFirst(event) {
  const cache = await caches.open(RUNTIME_CACHE);
  const key = hrefOf(CONFIG_REL);
  let response = null;
  try {
    response = await fetch(event.request);
  } catch (error) {
    const hit = await cache.match(key, { ignoreSearch: true });
    if (hit) return hit;
    throw error;
  }
  if (response.ok) {
    event.waitUntil(cache.put(key, response.clone()).catch(() => {}));
    return response;
  }
  const hit = await cache.match(key, { ignoreSearch: true });
  return hit || response;
}

async function onDemandFirst(event, entry) {
  const cache = await caches.open(ONDEMAND_CACHE);
  const key = onDemandKey(entry);
  const hit = await cache.match(key);
  if (hit) return hit;
  const response = await fetch(event.request);
  if (response.status === 200 && response.type !== 'opaque') {
    event.waitUntil(cache.put(key, response.clone()).catch(() => {}));
  }
  return response;
}

// CDN fonts and CanvasKit: only CORS-readable responses are stored, since
// opaque ones weigh on the quota and fail under COEP.
async function revalidating(event) {
  const cache = await caches.open(RUNTIME_CACHE);
  const hit = await cache.match(event.request);
  const refresh = fetch(event.request).then(async (response) => {
    if (response.ok && response.type === 'cors') {
      await cache.put(event.request, response.clone());
      await trimRuntime(cache);
    }
    return response;
  });
  if (hit) {
    event.waitUntil(refresh.catch(() => {}));
    return hit;
  }
  return refresh;
}

async function trimRuntime(cache) {
  const keys = await cache.keys();
  const excess = keys.slice(0, Math.max(0, keys.length - RUNTIME_MAX_ENTRIES));
  for (const key of excess) await cache.delete(key);
}
''';
