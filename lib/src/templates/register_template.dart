/// Arquivo: register_template.dart
/// Módulo: pillar_web_sw / modelo do registro
/// Descrição: JavaScript source of app-sw-register.js, loaded by the app's
///   index.html with a plain script tag.
/// Dependências: nenhuma.
/// Premissas: registers after the window `load` event so the first paint is
///   not delayed. The only public surface is the DOM event
///   `app-sw-update-available` (detail.registration); to apply the update
///   the app posts `{type: 'app-sw-skip-waiting'}` to `registration.waiting`
///   and reloads on `controllerchange`. Text and placement of the notice are
///   the app's decision.
/// Edge Cases: never throws; no service worker support or a failed
///   registration only leaves the app without offline shell.
library;

const registerScript = r'''
'use strict';

// Generated by pillar_web_sw. Fires `app-sw-update-available` on window when
// a new release is installed and waiting behind a running one.
(function () {
  if (!('serviceWorker' in navigator)) return;
  const script = document.currentScript;
  const origin = (script && script.src) || document.baseURI;

  function notify(registration) {
    try {
      window.dispatchEvent(
        new CustomEvent('app-sw-update-available', {
          detail: { registration: registration },
        }),
      );
    } catch (_) {
      // A broken listener must not break registration.
    }
  }

  function watch(registration) {
    if (registration.waiting && navigator.serviceWorker.controller) {
      notify(registration);
    }
    registration.addEventListener('updatefound', function () {
      const worker = registration.installing;
      if (!worker) return;
      worker.addEventListener('statechange', function () {
        if (worker.state === 'installed' && navigator.serviceWorker.controller) {
          notify(registration);
        }
      });
    });
  }

  function register() {
    try {
      navigator.serviceWorker
        .register(new URL('app-service-worker.js', origin).href, {
          scope: new URL('./', origin).href,
          updateViaCache: 'none',
        })
        .then(watch)
        .catch(function (error) {
          console.warn('[app-sw] registration failed', error);
        });
    } catch (error) {
      console.warn('[app-sw] registration failed', error);
    }
  }

  if (document.readyState === 'complete') register();
  else window.addEventListener('load', register, { once: true });
})();
''';
