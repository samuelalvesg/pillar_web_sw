/// Arquivo: kill_switch_template.dart
/// Módulo: pillar_web_sw / modelo do interruptor
/// Descrição: JavaScript source of the emergency worker published under the
///   same file name: it wipes the app caches and unregisters itself.
/// Dependências: nenhuma.
/// Premissas: no fetch listener, so pages go straight to the network.
/// Edge Cases: only caches starting with `<prefix>-` are removed; the
///   Flutter legacy caches and other apps on the origin are left alone.
library;

/// Placeholder replaced by the JSON-encoded cache prefix.
const prefixToken = '__APP_SW_PREFIX__';

const killSwitchTemplate = r'''
'use strict';

// Generated by pillar_web_sw --kill-switch. Removes the app caches and
// unregisters itself; open tabs keep running until they are reloaded.
const PREFIX = __APP_SW_PREFIX__;

self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      const mine = names.filter((n) => n.startsWith(PREFIX + '-'));
      await Promise.all(mine.map((n) => caches.delete(n)));
      await self.registration.unregister();
    })(),
  );
});
''';
